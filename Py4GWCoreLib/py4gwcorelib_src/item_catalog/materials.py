def material(model_id: int) -> Material | None:
    return _BY_MODEL_ID.get(int(model_id))


def material_model_ids() -> set[int]:
    return set(_BY_MODEL_ID)


def salvages_into(item_model_id: int) -> tuple[tuple[int, ...], tuple[int, ...]]:
    """``(common, rare)`` material ids this item salvages into. Empty when unrecorded."""
    return SALVAGE_MAP.get(int(item_model_id), ((), ()))


def salvages_into_material(item_model_id: int, material_model_id: int) -> bool:
    common, rare = salvages_into(item_model_id)
    material_model_id = int(material_model_id)
    return material_model_id in common or material_model_id in rare


def known_sources(material_model_id: int) -> int:
    """How many items are RECORDED as salvaging into a material. 0 means unrecorded, not impossible."""
    return len(_SOURCES.get(int(material_model_id), ()))
