from __future__ import annotations

from dataclasses import dataclass


# Outpost -> farm map -> farm -> /resign -> outpost -> next run.
FLOW_DIRECT = "direct"

# Outpost -> transit map -> farm map -> farm -> /resign -> outpost -> next run.
FLOW_TWO_MAP = "two_map"

# First run: outpost -> reset/transit map -> farm map.
# Next runs: farm map -> reset map -> farm map -> farm again, without replaying
# the long initial outpost/transit route.
FLOW_PORTAL_LOOP = "portal_loop"

# Custom multi-map setup/reset route built from setup_actions/reset_actions.
# Example Sandblasted:
#   first run: outpost -> farm map (setup route) -> transition map -> farm map;
#   next runs: farm map -> transition map -> farm map -> farm again.
FLOW_ROUTE_LOOP = "route_loop"

# Outpost -> challenge entry -> challenge/farm map -> farm -> /resign -> outpost.
FLOW_CHALLENGE = "challenge"

# Outpost -> NPC/dialog entry -> farm map -> farm -> /resign -> outpost.
FLOW_DIALOG = "dialog"

# Temple of the Ages -> /kneel + Balthazar dialogs -> Fissure of Woe
# -> farm -> /resign -> Temple of the Ages.
FLOW_FOW = "fow"


ExchangeAction = tuple[str, tuple[float, float], int]
# kind, expected_map_id, point, target_map_id, dialog_id
FarmRouteAction = tuple[str, int, tuple[float, float], int, int]


@dataclass(frozen=True)
class FarmDefinition:
    # Route semantics for coordinate-only path fields:
    #   farm_path          = AGGRO (VanquishNode / combat-aware movement)
    #   transit_path       = AGGRO (VanquishNode / combat-aware movement)
    #   outpost_path       = MOVE  (plain movement, no combat clearing)
    #   collector_route    = MOVE  (plain movement to the collector)
    #   balthazar_approach = MOVE  (plain movement before /kneel)
    #
    # Action-based routes are different: every point MUST carry its own mode.
    #   exchange_actions = ('move' | 'aggro' | 'exit', point, target_map_id)
    #   setup/reset      = ('move' | 'aggro' | 'exit' | 'dialog', ...)
    #
    # Single coordinates such as exit_point, portal_to_farm, portal_back,
    # entry_position, collector_position and nicholas_position are consumed by
    # dedicated nodes and therefore do not need a 'move'/'aggro' prefix.
    key: str
    name: str
    model_id: int
    default_target: int
    flow: str
    outpost_map_id: int
    farm_path: tuple[tuple[float, float], ...]

    farm_map_id: int = 0
    exit_point: tuple[float, float] | None = None
    clear_radius: str = "Earshot"

    transit_map_id: int = 0
    transit_path: tuple[tuple[float, float], ...] = ()
    reset_map_id: int = 0
    portal_to_farm: tuple[float, float] | None = None
    portal_back: tuple[float, float] | None = None

    # Optional granular route data.
    # outpost_path is walked before the normal outpost -> farm transition.
    # setup_actions / reset_actions support farms that cross several maps,
    # revisit the same map, or require a dialog before the farm loop.
    outpost_path: tuple[tuple[float, float], ...] = ()
    setup_actions: tuple[FarmRouteAction, ...] = ()
    reset_actions: tuple[FarmRouteAction, ...] = ()

    challenge_delay_ms: int = 0
    entry_position: tuple[float, float] | None = None
    entry_dialog: int = 0

    balthazar_approach: tuple[tuple[float, float], ...] = ()
    balthazar_champion_model_id: int = 0

    # Nicholas exchange metadata.
    nicholas_item_name: str = ""
    items_for_5_gifts: int = 0
    collector_item_name: str = ""
    collector_item_model_id: int = 0

    # Collector conversion metadata.
    #
    # collector_mode:
    #   ""       = no conversion
    #   "town"   = travel to a collector outpost before the Nicholas route
    #   "inline" = collector is encountered during exchange_actions
    #   "manual" = source data has no reliable collector position
    collector_mode: str = ""
    collector_exchange_rate: int = 0
    collector_target_count: int = 5
    collector_town_map_id: int = 0
    collector_route: tuple[tuple[float, float], ...] = ()
    collector_position: tuple[float, float] | None = None
    collector_insert_after: int = -1

    exchange_town_map_id: int = 0
    exchange_actions: tuple[ExchangeAction, ...] = ()
    nicholas_position: tuple[float, float] | None = None
    exchange_source_file: str = ""

    @property
    def exchange_available(self) -> bool:
        return (
            self.exchange_town_map_id > 0
            and bool(self.exchange_actions)
            and self.nicholas_position is not None
        )

    @property
    def requires_collector_conversion(self) -> bool:
        return bool(self.collector_item_name)


